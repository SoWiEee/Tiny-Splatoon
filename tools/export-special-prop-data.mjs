import { register } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
register(new URL('./reference-loader.mjs', import.meta.url));
const { getSpecialProp } = await import('../splat-ref/src/game/special-props.js');
const crab = getSpecialProp('crab');
const source = new URL('../splat-ref/src/game/special-props.js', import.meta.url);
const out = `// Generated by tools/export-special-prop-data.mjs. Do not edit.\n#pragma once\n#include <glm/glm.hpp>\nnamespace restoration {\n// Source SHA-256: ${createHash('sha256').update(readFileSync(source)).digest('hex')}\n${['gunMuzzle','cannonMuzzle','seatAt'].map(key => `inline const glm::dvec3 Crab${key[0].toUpperCase()+key.slice(1)}{${crab[key].toArray().map(n=>n.toPrecision(17)).join(',')}};`).join('\n')}\n}\n`;
const path = new URL('../restoration/SpecialPropData.hpp', import.meta.url);
if(process.argv.includes('--check')) { if(readFileSync(path,'utf8')!==out) throw new Error('Stale special prop data'); }
else writeFileSync(path,out);
console.log('Verified source Crab muzzles and rider seat');
