import { register } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

register(new URL('./reference-loader.mjs', import.meta.url));
const { MAPS } = await import('../splat-ref/src/config.js');
const { MAP_LAYOUTS } = await import('../splat-ref/src/world/maps.js');
const { layoutFor, inMode } = await import('../splat-ref/src/world/variants.js');
const { dressingFor } = await import('../splat-ref/src/world/dressing.js');
const { PropKit } = await import('../splat-ref/src/world/props.js');
const { Level } = await import('../splat-ref/src/world/level.js');
const { PaintSystem } = await import('../splat-ref/src/world/paint.js');
const { ZONE_DEFS } = await import('../splat-ref/src/world/zones-data.js');
const { ZoneControl } = await import('../splat-ref/src/game/zones.js');
const { G } = await import('../splat-ref/src/core/ctx.js');

const output = resolve(import.meta.dirname, '../tests/fixtures/zone_control_fixtures.hpp');
const args = process.argv.slice(2);
const check = args.includes('--check');
if (args.some((arg) => arg !== '--check') || args.filter((arg) => arg === '--check').length > 1)
  throw new Error('Usage: node tools/export-zone-fixtures.mjs [--check]');

const sourcePaths = [
  'src/config.js', 'src/world/maps.js', 'src/world/variants.js', 'src/world/dressing.js',
  'src/world/props.js', 'src/world/level.js', 'src/world/paint.js',
  'src/world/zones-data.js', 'src/game/zones.js',
];
const sources = await Promise.all(sourcePaths.map(async (path) => ({
  path,
  sha256: createHash('sha256').update(await readFile(new URL(`../splat-ref/${path}`, import.meta.url))).digest('hex'),
})));

const stages = [];
for (const id of Object.keys(ZONE_DEFS)) {
  const map = MAPS.find((entry) => entry.id === id);
  const layout = MAP_LAYOUTS[map?.layout || id];
  if (!map || !layout) throw new Error(`Missing source Zones map: ${id}`);

  const kit = new PropKit(null, { quality: 'high', headless: true });
  const colliders = [];
  try {
    for (const item of dressingFor(map.layout || id))
      if (inMode(item, 'zones')) colliders.push(...kit.add(item.type, item).colliders);
  } finally {
    kit.dispose();
  }

  G.level = new Level(layoutFor(layout, 'zones'), colliders);
  const paint = Object.create(PaintSystem.prototype);
  Object.assign(paint, { level: G.level, size: 4096, cell: 0.25, pad: 8 });
  paint._layout(30);
  paint._initGrid();
  G.paint = paint;
  G.time = 0;

  const match = { time: 300, state: 'intro', local: { team: 0 } };
  match.zones = new ZoneControl(match);
  stages.push({
    id,
    zones: match.zones.zones.map((zone) => ({ cells: [...zone.cells], center: zone.center, reach: zone.reach })),
  });
}

if (stages.length !== 7) throw new Error(`Expected seven source Zones maps; got ${stages.length}`);

const number = (value) => Object.is(value, -0) ? '0' : Number(value).toString();
const cells = (values) => {
  const rows = [];
  for (let i = 0; i < values.length; i += 14) rows.push(`        ${values.slice(i, i + 14).join(', ')}`);
  return rows.length ? `\n${rows.join(',\n')}\n      ` : '';
};
const zones = stages.map(({ id, zones: items }) => {
  const zoneRows = items.map((zone) =>
    `      ZoneFixture{{${cells(zone.cells)}}, {${zone.center.map(number).join(', ')}}, ${number(zone.reach)}}`).join(',\n');
  return `    StageFixture{"${id}", {\n${zoneRows}\n    }}`;
}).join(',\n');
const hashes = sources.map(({ path, sha256 }) => `// ${path} sha256 ${sha256}`).join('\n');
const content = `#pragma once
// Generated by tools/export-zone-fixtures.mjs from source Level, PaintSystem, and ZoneControl; do not hand edit.
${hashes}
#include <array>
#include <string_view>
#include <vector>
#include <glm/glm.hpp>

namespace restoration::zone_fixtures {
struct ZoneFixture { std::vector<int> cells; glm::dvec3 center; double reach; };
struct StageFixture { std::string_view id; std::vector<ZoneFixture> zones; };
inline const std::array<StageFixture, 7> source{{
${zones}
}};
} // namespace restoration::zone_fixtures
`;

if (check) {
  const old = (await readFile(output, 'utf8')).replace(/\r\n/g, '\n');
  if (old !== content) throw new Error('Stale source Zones fixtures; run node tools/export-zone-fixtures.mjs');
} else {
  await writeFile(output, content);
}
console.log(`Source Zones fixtures: ${stages.length} stages`);
