import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { register } from 'node:module';
import { resolve } from 'node:path';

const root=resolve(import.meta.dirname,'..');
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(arg=>arg!=='--check'))throw new Error('Usage: node tools/export-character-render-data.mjs [--check]');
execFileSync(process.execPath,['tools/export-reference.mjs','--check'],{cwd:root,stdio:'pipe'});
register(new URL('./reference-loader.mjs',import.meta.url));
const { Color }=await import('three');
const { makeSkinMaterial,makeCharUniforms }=await import('../splat-ref/src/game/character-mats.js');
const catalog=JSON.parse(await readFile(resolve(root,'assets/reference/characters/catalog.json'),'utf8'));
const manifest=JSON.parse(await readFile(resolve(root,'assets/reference/characters/shaders/manifest.json'),'utf8'));
const number=value=>{if(!Number.isFinite(value))throw new Error('Non-finite source render value');return Number.isInteger(value)?`${value}.0`:String(value);};
const vector=value=>`{${value.map(number).join(',')}}`;
const color=value=>vector(new Color(value).toArray());
const quote=JSON.stringify;
const styles=catalog.styles;
const threeSource=await readFile(resolve(root,'splat-ref/vendor/three/build/three.module.js'),'utf8');
const dfgBlock=threeSource.match(/const DATA = new Uint16Array\( \[([\s\S]*?)\] \);\s*let lut = null;\s*function getDFGLUT/);
if(!dfgBlock)throw new Error('Source DFG lookup table not found');
const dfg=dfgBlock[1].split(',').map(v=>v.trim()).filter(Boolean);
if(dfg.length!==512||dfg.some(v=>!/^0x[0-9a-f]{4}$/.test(v)))throw new Error('Invalid source 16x16 RG16F DFG table');
if(styles.skin.length!==9||styles.outfits.length!==10||styles.iris.length!==8||styles.presets.length!==10)throw new Error('Incomplete source styles');
let out=`// Generated by tools/export-character-render-data.mjs; source material defaults and linear palettes.\n#pragma once\n#include "CharacterPose.hpp"\n#include <map>\n\nnamespace restoration {\nstruct CharacterMaterialDefinition {\n    std::string key;\n    bool skinned, transparent, depthWrite, depthTest, premultipliedAlpha;\n    int side, blending, depthFunc;\n    std::map<std::string,std::vector<double>> uniforms;\n};\ninline const std::vector<CharacterMaterialDefinition>& CharacterMaterials() {\n    static const std::vector<CharacterMaterialDefinition> values={\n`;
for(const entry of manifest.entries){
    const s=entry.renderState;
    if(![3,6].includes(s.depthFunc)||![0,1,2].includes(s.blending))throw new Error(`Unsupported source render state: ${entry.key}`);
    out+=`        {${quote(entry.key)},${entry.skinned},${s.transparent},${s.depthWrite},${s.depthTest},${s.premultipliedAlpha},${s.side},${s.blending},${s.depthFunc},{\n`;
    for(const [key,value] of Object.entries(entry.uniforms)){
        const values=Array.isArray(value)?value.flat(Infinity):[typeof value==='boolean'?Number(value):value];
        if(!values.every(v=>typeof v==='number'&&Number.isFinite(v)))throw new Error(`Unsupported uniform ${key}`);
        if(values.length)out+=`            {${quote(key)},${vector(values)}},\n`;
    }
    out+='        }},\n';
}
out+=`    };\n    return values;\n}\ninline const std::array<glm::dvec3,9> CharacterSkin={{${styles.skin.map(color).join(',')}}};\ninline const std::array<std::array<glm::dvec3,2>,8> CharacterIris={{${styles.iris.map(pair=>`{{${pair.map(color).join(',')}}}`).join(',')}}};\ninline CharacterMaterialState CharacterOutfit(int index) {\n    CharacterMaterialState m;\n    switch(index) {\n`;
styles.outfits.forEach((style,i)=>{
    out+=`    case ${i}: `;
    for(const key of ['shirt','shorts','shoe','sole','sock','strap'])out+=`m.${key}=${color(style[key])};`;
    out+=`m.pattern=${number(style.pattern)};break;\n`;
});
out+=`    default: throw std::invalid_argument("Unknown source outfit");\n    }\n    return m;\n}\nstruct CharacterStyle { int hair=0,skin=0,outfit=0,eyes=0,hat=0,brows=0; };\nstruct CharacterPreset { const char* id; const char* name; CharacterStyle style; };\ninline const std::array<CharacterPreset,10> CharacterPresets={{\n`;
for(const preset of styles.presets)out+=`    {${quote(preset.id)},${quote(preset.name)},{${['hair','skin','outfit','eyes','hat','brows'].map(key=>preset.style[key]).join(',')}}},\n`;
out+='}};\n';
out+='struct CharacterSkinParameters { double luminance,freckle; glm::dvec3 scatter,tint; };\ninline const std::array<CharacterSkinParameters,9> CharacterSkinLighting={{\n';
for(const skin of styles.skin){
    const u=makeCharUniforms(),m=makeSkinMaterial(u,skin),shader={uniforms:{},vertexShader:'#include <common>',fragmentShader:'#include <common>'};
    m.onBeforeCompile(shader,null);
    out+=`    {${number(shader.uniforms.uSkinLum.value)},${number(u.uFreckle.value)},${vector(shader.uniforms.uSSSW.value.toArray())},${vector(shader.uniforms.uSSSTint.value.toArray())}},\n`;
    m.dispose();
}
out+='}};\n';
out+=`// Three.js DFG LUT (MIT), copied as half-float bits from the bundled reference renderer.\ninline constexpr std::array<std::uint16_t,512> CharacterDfg={{${dfg.join(',')}}};\n}\n`;
out=out.replace('#include <map>','#include <map>\n#include <stdexcept>');
const path=resolve(root,'src/render/CharacterRenderData.hpp');
if(check){if(await readFile(path,'utf8')!==out)throw new Error('Stale native character render data');}
else await writeFile(path,out);
console.log(`${check?'Verified':'Exported'} ${manifest.entries.length} native materials, 9 skin, 10 outfit, 8 iris, 10 preset palettes`);
