import { register } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
register(new URL('./reference-loader.mjs', import.meta.url));
const { ZONE_DEFS } = await import('../splat-ref/src/world/zones-data.js');
if (process.argv.slice(2).some(v => v !== '--check')) throw new Error('Usage: node tools/export-zone-data.mjs [--check]');
const source = await readFile(new URL('../splat-ref/src/world/zones-data.js', import.meta.url));
const polygon = p => '{' + p.map(([x,z]) => `{${x},${z}}`).join(',') + '}';
const zone = z => '{{' + (z.polys || [z.poly]).map(polygon).join(',') + `},${z.y0 ?? -2},${z.y1 ?? 6}}`;
const rows = Object.entries(ZONE_DEFS).map(([id, def]) => `        {"${id}",{${def.center.map(zone).join(',')}},${zone(def.side)}},`);
const output = `// Generated by tools/export-zone-data.mjs; exact source toFixed polygon coordinates.
// splat-ref/src/world/zones-data.js SHA256 ${createHash('sha256').update(source).digest('hex')}
#include "ZoneControl.hpp"
#include <array>
namespace restoration {
const ZoneStageDefinition* FindZoneStageDefinition(std::string_view stageId) noexcept {
    static const std::array<ZoneStageDefinition,${rows.length}> data{{
${rows.join('\n')}
    }};
    for(const auto& item:data)if(item.stageId==stageId)return &item;
    return nullptr;
}
}
`;
const file = new URL('../src/game/ZoneData.cpp', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(file, 'utf8')).replace(/\r\n/g,'\n') !== output) throw new Error('Stale native zone definitions');
} else await writeFile(file, output);
console.log(`Source zone definitions: ${rows.length} stages`);
