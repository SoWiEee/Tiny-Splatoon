import { register } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

register(new URL('./reference-loader.mjs', import.meta.url));
const THREE = await import('three');
const { G } = await import('../splat-ref/src/core/ctx.js');
const { CameraRig } = await import('../splat-ref/src/game/cameraRig.js');
const { Level } = await import('../splat-ref/src/world/level.js');
const { Physics } = await import('../splat-ref/src/game/physics.js');

const root = resolve(import.meta.dirname, '..');
const floor = { kind: 'box', min: [-20, -1, -20], max: [20, 0, 20] };
const wall = { kind: 'box', min: [-2, 0, -3], max: [2, 3, -2.5] };
const layout = (blocked) => ({
  bounds: { minX: -20, maxX: 20, minZ: -20, maxZ: 20 },
  spawnPads: [[0, 0, 0], [5, 0, 5]], spawnBarrier: 0,
  single: blocked ? [floor, wall] : [floor], half: [],
});

const scenes = [
  { blocked: false, yaw: 0, pitch: -0.1, frames: [
    {}, { dt: 1 / 30, vel: [5, 0, 0], pos: [0.08, 0, 0] },
    { vel: [5, 0, 0], pos: [0.16, 0, 0], squid: true, swim: true },
    { vel: [9, 5, 0], pos: [0.3, 0.08, 0], squid: true, swim: true, grounded: false },
    { vel: [2, 1, 0], pos: [0.34, 0.4, 0], visual: [0.34, 0.43, 0], grounded: false },
    { vel: [2, -7, 0], pos: [0.38, -0.4, 0], grounded: false },
    { vel: [0, 0, 0], pos: [0.4, 0, 0], landT: 0, landSpeed: 10 },
    { dt: 1 / 120, vel: [0, 0, 0], pos: [0.4, 0, 0], landT: 0.016, landSpeed: 10 },
    { vel: [0, 0, 0], pos: [12, 0, 0] },
  ] },
  { blocked: true, yaw: 0, pitch: -0.1, frames: [
    {}, {}, {}, { vel: [-6, 0, 0], pos: [-0.1, 0, 0], climbing: true }, {}, {},
  ] },
  { blocked: false, yaw: 0.4, pitch: 0.7, frames: [
    {}, {}, { dt: 0.05, recoil: 0.025 }, {}, {},
  ] },
];
const vec = (a) => a.map((x) => Number(x).toPrecision(17)).join(', ');
const rows = [];
for (const scene of scenes) {
  const level = new Level(layout(scene.blocked));
  G.level = level; G.physics = new Physics(level); G.settings = { fov: 82, cameraShake: 0 };
  G.match = { attract: true };
  const cam = new THREE.PerspectiveCamera(60, 16 / 9, 0.15, 6500);
  const rig = new CameraRig(cam);
  rig.yaw = scene.yaw; rig.pitch = scene.pitch;
  const actor = {
    pos: new THREE.Vector3(), vel: new THREE.Vector3(), visual: new THREE.Vector3(),
    form: 'kid', anim: { form: 'kid' }, grounded: true, climbing: false,
    landT: 99, landSpeed: 0, visualPos(out) { return out.copy(this.visual); },
  };
  rig.follow(actor, true);
  rig._prevMode = 'follow'; rig._prevTarget = actor;
  for (let i = 0; i < scene.frames.length; i++) {
    const frame = scene.frames[i];
    actor.pos.set(...(frame.pos || [0, 0, 0]));
    actor.visual.set(...(frame.visual || frame.pos || [0, 0, 0])); actor.vel.set(...(frame.vel || [0, 0, 0]));
    actor.form = frame.squid ? 'squid' : 'kid';
    actor.anim.form = frame.climbing ? 'climb' : frame.swim ? 'swim' : 'kid';
    actor.grounded = frame.grounded ?? true;
    actor.climbing = !!frame.climbing;
    actor.landT = frame.landT ?? 99; actor.landSpeed = frame.landSpeed ?? 0;
    if (frame.recoil) rig.recoil(frame.recoil);
    const dt = frame.dt ?? 1 / 60;
    rig.update(dt);
    const forward = new THREE.Vector3(0, 0, -1).applyQuaternion(cam.quaternion);
    rows.push(`  { ${scene.blocked}, ${i === 0}, ${dt}, ${scene.yaw}, ${scene.pitch}, ${frame.recoil || 0},` +
      ` {${vec(actor.pos.toArray())}}, {${vec(actor.visual.toArray())}}, {${vec(actor.vel.toArray())}}, ${actor.grounded}, ${actor.climbing}, ${!!frame.squid}, ${!!frame.swim},` +
      ` ${actor.landT}, ${actor.landSpeed}, {${vec(cam.position.toArray())}}, {${vec(forward.toArray())}}, ${cam.fov.toPrecision(17)} },`);
  }
}
const output = `// Generated by node tools/export-camera-fixtures.mjs from the reference CameraRig and Physics.\n#pragma once\n#include <array>\n#include <glm/vec3.hpp>\nnamespace restoration::camera_fixtures {\nstruct Frame {\n    bool blocked, reset; double dt, yaw, pitch, recoil;\n    glm::dvec3 position, visualPosition, velocity; bool grounded, climbing, squid, swimming;\n    double landT, landSpeed; glm::dvec3 eye, forward; double verticalFovDegrees;\n};\ninline const std::array<Frame, ${rows.length}> frames{{\n${rows.join('\n')}\n}};\n}\n`;
const target=resolve(root, 'tests/fixtures/camera_fixtures.hpp');
if(process.argv.includes('--check')) {
  if(readFileSync(target,'utf8')!==output) throw new Error('Camera fixtures differ from reference CameraRig');
} else writeFileSync(target, output);
console.log(`${process.argv.includes('--check')?'verified':'wrote'} ${rows.length} camera reference frames`);
