import { register } from 'node:module';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';

const root=resolve(import.meta.dirname,'..');
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(arg=>arg!=='--check')) throw new Error('Usage: node tools/export-arsenal.mjs [--check]');
execFileSync(process.execPath,['tools/export-reference.mjs','--check'],{cwd:root,stdio:'pipe'});
register(new URL('./reference-loader.mjs',import.meta.url));
const config=await import('../splat-ref/src/config.js');
const groups=[['main',config.WEAPON_ORDER,config.WEAPONS],['sub',config.SUB_ORDER,config.SUBS],['special',config.SPECIAL_ORDER,config.SPECIALS]];
if(groups.map(([,ids])=>ids.length).join('/')!=='12/15/19') throw new Error('Active arsenal roster differs from locked spec');
const entries=[];
for(const [category,ids,definitions] of groups) for(const id of ids) {
    if(!definitions[id] || definitions[id].id!==id) throw new Error(`Missing definition ${category}/${id}`);
    entries.push({category,...definitions[id]});
}
const manifest={schema:1,sourceHash:createHash('sha256').update(await readFile(resolve(root,'splat-ref/src/config.js'))).digest('hex'),
    main:config.WEAPON_ORDER,sub:config.SUB_ORDER,special:config.SPECIAL_ORDER,definitions:entries,
    player:config.PLAYER,difficulties:config.DIFFICULTY,match:config.MATCH,botNames:config.BOT_NAMES};
const quote=JSON.stringify;
function flatten(value,path='',out=[]) {
    if(typeof value==='number') {
        if(!Number.isFinite(value)) throw new Error(`Non-finite tuning ${path}`);
        out.push([path,'Number',value,'']);
    } else if(typeof value==='boolean') out.push([path,'Boolean',Number(value),'']);
    else if(typeof value==='string') out.push([path,'String',0,value]);
    else if(value===null) out.push([path,'Null',0,'']);
    else if(typeof value==='object') {
        const pairs=Object.entries(value);
        out.push([path,Array.isArray(value)?'Array':'Object',pairs.length,'']);
        for(const [key,child] of pairs) {
            if(key.includes('.')) throw new Error(`Ambiguous tuning key: ${key}`);
            flatten(child,path?`${path}.${key}`:key,out);
        }
    } else throw new Error(`Unsupported tuning ${path}: ${typeof value}`);
    return out;
}
let index=0;
const tables=[];
function definition(value,fallbackId='') {
    const table=`fields${index++}`,fields=flatten(value);
    tables.push(`static const TuningField ${table}[]={\n${fields.map(([path,type,number,text])=>`    {${quote(path)},TuningType::${type},${Object.is(number,-0)?'0':String(number)},${quote(text)}},`).join('\n')}\n};`);
    return `{${quote(value.id||fallbackId)},${quote(value.name||'')},${quote(value.kind||'')},${quote(value.sub||'')},${quote(value.special||'')},${table},std::size(${table})}`;
}
const definitions=entries.map(entry=>definition(Object.fromEntries(Object.entries(entry).filter(([key])=>key!=='category'))));
const player=definition(config.PLAYER,'player'),match=definition(config.MATCH,'match');
const difficulties=Object.entries(config.DIFFICULTY).map(([id,value])=>definition(value,id));
const ranges=[definitions.slice(0,12),definitions.slice(12,27),definitions.slice(27)];
const functions=['MainEquipment','SubEquipment','SpecialEquipment'].map((name,i)=>`const std::vector<EquipmentData>& ${name}(){\n    static const std::vector<EquipmentData> data={\n${ranges[i].map(row=>'        '+row+',').join('\n')}\n    };return data;\n}`);
const cpp=`// Generated by node tools/export-arsenal.mjs; source config SHA-256 ${manifest.sourceHash}\n#include "ArsenalData.hpp"\n#include <iterator>\nnamespace restoration {\nnamespace {\n${tables.join('\n')}\n}\n${functions.join('\n')}\nconst EquipmentData& GetEquipment(EquipmentCategory category,std::string_view id){\n    const std::vector<EquipmentData>* data=nullptr;\n    switch(category){case EquipmentCategory::Main:data=&MainEquipment();break;case EquipmentCategory::Sub:data=&SubEquipment();break;case EquipmentCategory::Special:data=&SpecialEquipment();break;}\n    if(data)for(const auto& entry:*data)if(entry.id==id)return entry;\n    throw std::invalid_argument("Unknown equipment ID: "+std::string(id));\n}\nconst EquipmentData& PlayerTuning(){static const EquipmentData data=${player};return data;}\nconst EquipmentData& MatchTuning(){static const EquipmentData data=${match};return data;}\nconst EquipmentData& DifficultyTuning(std::string_view id){\n    static const EquipmentData data[]={${difficulties.join(',')}};\n    for(const auto& entry:data)if(entry.id==id)return entry;\n    throw std::invalid_argument("Unknown difficulty: "+std::string(id));\n}\nconst std::vector<std::string_view>& BotNames(){static const std::vector<std::string_view> data={${config.BOT_NAMES.map(quote).join(',')}};return data;}\n}\n`;
for(const [file,content] of [['assets/reference/arsenal.json',JSON.stringify(manifest,null,2)+'\n'],['restoration/ArsenalData.cpp',cpp]]) {
    const target=resolve(root,file);
    if(check) {if(await readFile(target,'utf8')!==content) throw new Error(`Stale arsenal artifact: ${file}`);}
    else {await mkdir(dirname(target),{recursive:true});await writeFile(target,content);}
}
console.log(`${check?'Verified':'Exported'} 12 main / 15 sub / 19 special definitions and complete nested tuning`);
