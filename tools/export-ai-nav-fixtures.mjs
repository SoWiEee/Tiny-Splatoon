import { register } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
register(new URL('./reference-loader.mjs', import.meta.url));
const { OFFLINE_MAPS } = await import('../splat-ref/src/config.js');
const { MAP_LAYOUTS } = await import('../splat-ref/src/world/maps.js');
const { layoutFor, inMode } = await import('../splat-ref/src/world/variants.js');
const { dressingFor } = await import('../splat-ref/src/world/dressing.js');
const { PropKit } = await import('../splat-ref/src/world/props.js');
const { Level } = await import('../splat-ref/src/world/level.js');
const { Physics } = await import('../splat-ref/src/game/physics.js');
const { NavGraph } = await import('../splat-ref/src/game/nav.js');
const THREE = await import('three');

const number = (x) => Number(x.toFixed(8));
const exactNumber = (x) => Number.isInteger(x) ? `${x}.0` : x.toString();
const vec = (v) => `{${number(v.x)}, ${number(v.y)}, ${number(v.z)}}`;
const rayReport = process.argv.includes('--ray-report');
const radialDirections = Array.from({ length: 8 }, (_, k) => {
  const angle = (k / 8) * Math.PI * 2;
  return { x: Math.cos(angle), z: Math.sin(angle) };
});
const sourceRays = [];
const lines = [
  '#pragma once',
  '// Generated by tools/export-ai-nav-fixtures.mjs from locked splat-ref/src/game/nav.js.',
  '#include <array>',
  '#include <vector>',
  '#include <glm/vec3.hpp>',
  'namespace restoration::ai_fixtures {',
  'struct Probe { glm::dvec3 pos; double maxUp; bool start; int nearest; };',
  'struct Route { int from, to, team; bool noClimb; std::vector<int> nodes; };',
  'struct Climb { int from, to; glm::dvec3 wallPoint; glm::dvec2 wallNormal; double topY; };',
  'struct SourceRay { const char* stage; int node, radial; double maxDist; bool skipGrates, hit; int block, face; double distance; glm::dvec3 point, normal; };',
  'struct Stage { const char* id; int nodeCount, validCount; std::array<int, 4> edgeCounts;',
  '  std::array<Probe, 9> probes; std::array<Route, 3> routes; std::vector<Climb> climbs; };',
  'inline const std::array<Stage, 7> stages{{',
];

for (const map of OFFLINE_MAPS) {
  const layout = MAP_LAYOUTS[map.layout || map.id];
  const kit = new PropKit(null, { quality: 'high', headless: true });
  const colliders = [];
  try {
    for (const item of dressingFor(map.layout || map.id)) {
      if (!inMode(item, 'turf')) continue;
      colliders.push(...kit.add(item.type, item).colliders);
    }
  } finally { kit.dispose(); }
  const level = new Level(layoutFor(layout, 'turf'), colliders);
  for (const face of level.faces) if (face.paintable) face.atlas = true;
  const nav = new NavGraph(level, new Physics(level));
  if (map.id === 'crossmarket' || map.id === 'lockgate') {
    const nodeId = map.id === 'crossmarket' ? 420 : 1395;
    const node = nav.nodes[nodeId], dir = radialDirections[1];
    const hit = nav.physics.raycast(new THREE.Vector3(node.x, node.y + 0.35, node.z),
      new THREE.Vector3(dir.x, 0, dir.z), 1.3, undefined, true);
    sourceRays.push({ stage: map.id, node: nodeId, radial: 1, hit });
    if (rayReport) console.log(`${map.id}: source radial 1 node ${nodeId} hit=${hit.hit} block=${hit.block} face=${hit.face} distance=${hit.dist.toPrecision(17)} point=(${hit.point.x.toPrecision(17)},${hit.point.y.toPrecision(17)},${hit.point.z.toPrecision(17)}) normal=(${hit.normal.x},${hit.normal.y},${hit.normal.z})`);
  }
  const counts = { walk: 0, jump: 0, drop: 0, climb: 0 };
  for (const node of nav.nodes) for (const edge of node.nb) counts[edge.type]++;
  const climbs = [];
  for (const node of nav.nodes) for (const edge of node.nb) if (edge.type === 'climb')
    climbs.push(`Climb{${node.id}, ${edge.to}, ${vec({ x: edge.wallP[0], y: edge.wallP[1], z: edge.wallP[2] })}, {${number(edge.wallN[0])}, ${number(edge.wallN[1])}}, ${number(edge.topY)}}`);
  const [p0, p1] = level.spawnPads;
  const center = p0.clone().add(p1).multiplyScalar(0.5);
  const samples = [p0, p1, center,
    new THREE.Vector3((p0.x * 3 + p1.x) / 4, (p0.y * 3 + p1.y) / 4, (p0.z * 3 + p1.z) / 4),
    new THREE.Vector3((p0.x + p1.x * 3) / 4, (p0.y + p1.y * 3) / 4, (p0.z + p1.z * 3) / 4),
    ...[0.1, 0.3, 0.5, 0.7].map((f) => nav.nodes[nav.validIds[Math.floor((nav.validIds.length - 1) * f)]])];
  const probes = samples.map((p, i) => ({ pos: new THREE.Vector3(p.x, p.y, p.z), maxUp: i < 2 ? 1.2 : 0.8,
    start: i < 2, nearest: nav.nearest(p, i < 2 ? 1.2 : 0.8, i < 2) }));
  const a = probes[0].nearest, b = probes[1].nearest, c = probes[2].nearest;
  const routes = [[a, c, 0, false], [b, c, 1, false], [a, b, 0, true]].map(([from, to, team, noClimb]) =>
    ({ from, to, team, noClimb, nodes: nav.path(from, to, team, 6000, noClimb) || [] }));
  lines.push(`  Stage{"${map.id}", ${nav.nodes.length}, ${nav.validIds.length}, {${Object.values(counts).join(', ')}}, {`);
  for (const p of probes) lines.push(`    Probe{${vec(p.pos)}, ${p.maxUp}, ${p.start}, ${p.nearest}},`);
  lines.push('  }, {');
  for (const route of routes) lines.push(`    Route{${route.from}, ${route.to}, ${route.team}, ${route.noClimb}, {${route.nodes.join(', ')}}},`);
  lines.push(`  }, {${climbs.join(', ')} }},`);
  console.log(`${map.id}: ${nav.nodes.length} nodes, ${nav.validIds.length} valid, edges ${Object.values(counts).join('/')}`);
}
lines.push('}};');
lines.push('inline const std::array<SourceRay, 2> sourceRays{{');
for (const ray of sourceRays) {
  lines.push(`  SourceRay{"${ray.stage}", ${ray.node}, ${ray.radial}, 1.3, true, ${ray.hit.hit}, ${ray.hit.block}, ${ray.hit.face}, ${number(ray.hit.dist)}, ${vec(ray.hit.point)}, ${vec(ray.hit.normal)}},`);
}
lines.push('}};', '} // namespace restoration::ai_fixtures', '');
if (rayReport) process.exit(0);
const file = resolve(root, 'tests/ai_nav_fixtures.hpp');
const output = lines.join('\n');
const directionFile = resolve(root, 'src/game/NavDirections.hpp');
const directionOutput = [
  '#pragma once',
  '// Generated from the source Math.cos/sin radial samples in src/game/nav.js.',
  '#include <array>',
  '#include <glm/vec2.hpp>',
  'namespace restoration {',
  'inline constexpr std::array<glm::dvec2, 8> kSourceRadialDirections{{',
  ...radialDirections.map((d) => `  glm::dvec2{${exactNumber(d.x)}, ${exactNumber(d.z)}},`),
  '}};',
  '} // namespace restoration',
  '',
].join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== output) throw new Error('AI nav fixtures differ from locked source');
  if (await readFile(directionFile, 'utf8') !== directionOutput) throw new Error('Native nav directions differ from locked source Math.cos/sin values');
} else {
  await writeFile(file, output);
  await writeFile(directionFile, directionOutput);
}
